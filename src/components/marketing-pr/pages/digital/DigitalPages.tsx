// ============ SEO MANAGEMENT ============
export function SEOManagement() {
  const [search, setSearch] = useState('');
  const [selected, setSelected] = useState<SEOKeyword | null>(null);

  const filtered = seoKeywords.filter((k) => k.keyword.toLowerCase().includes(search.toLowerCase()));

  const columns: Column<SEOKeyword>[] = [
    { key: 'keyword', header: 'Keyword', render: (r) => <span className="font-medium text-foreground">{r.keyword}</span> },
    { key: 'rank', header: 'Current Rank', render: (r) => <span className="font-bold text-foreground">#{r.rank}</span> },
    { key: 'prev', header: 'Previous Rank', render: (r) => <span className="text-muted-foreground text-xs">#{r.previousRank}</span> },
    { key: 'change', header: 'Change', render: (r) => {
      const diff = r.previousRank - r.rank;
      return (
        <span className={`flex items-center gap-1 text-xs font-medium ${diff > 0 ? 'text-success' : diff < 0 ? 'text-destructive' : 'text-muted-foreground'}`}>
          {diff > 0 && <ArrowUp size={14} />}
          {diff < 0 && <ArrowDown size={14} />}
          {diff === 0 && <Minus size={14} />}
          {diff > 0 ? `+${diff}` : diff < 0 ? `${diff}` : 'No change'}
        </span>
      );
    }},
    { key: 'volume', header: 'Search Volume', render: (r) => <span className="text-muted-foreground text-xs">{r.searchVolume.toLocaleString()}</span> },
    { key: 'trend', header: 'Trend', render: (r) => (
      <Badge variant={r.trend === 'up' ? 'green' : r.trend === 'down' ? 'red' : 'slate'}>
        {r.trend === 'up' ? 'Improving' : r.trend === 'down' ? 'Declining' : 'Stable'}
      </Badge>
    )},
  ];

  return (
    <div>
      <PageHeader title="SEO Management" description="Improve the institution's visibility in search engines by monitoring keywords, website performance, and search rankings." />
      <div className="grid grid-cols-2 lg:grid-cols-4 gap-2 mb-3">
        <StatCard label="Tracked Keywords" value={seoKeywords.length} icon={<Search size={20} />} accent="blue" />
        <StatCard label="Top 10 Rankings" value={seoKeywords.filter((k) => k.rank <= 10).length} icon={<TrendingUp size={20} />} accent="green" />
        <StatCard label="Improving" value={seoKeywords.filter((k) => k.trend === 'up').length} icon={<ArrowUp size={20} />} accent="green" />
        <StatCard label="Declining" value={seoKeywords.filter((k) => k.trend === 'down').length} icon={<ArrowDown size={20} />} accent="red" />
      </div>
      <Card className="mb-3">
        <CardHeader title="Keyword Rankings" subtitle="Current vs previous search rankings" icon={<BarChart3 size={18} />} />
        <CardBody>
          <BarChart data={seoKeywords.map((k) => ({ label: k.keyword.split(' ').slice(0, 2).join(' '), value: k.rank, color: k.trend === 'up' ? 'bg-success/100' : k.trend === 'down' ? 'bg-destructive/80' : 'bg-slate-400' }))} />
        </CardBody>
      </Card>
      <Card>
        <CardHeader title="SEO Keywords" subtitle="All tracked keywords with rankings" icon={<Search size={18} />} />
        <div className="px-5 py-3 border-b border-border">
          <div className="w-full max-w-sm"><SearchInput value={search} onChange={setSearch} placeholder="Search keywords..." /></div>
        </div>
        <Table columns={columns} data={filtered} onRowClick={setSelected} emptyMessage="No keywords found" />
      </Card>
      <Drawer open={!!selected} onClose={() => setSelected(null)} title="Keyword Details" subtitle={selected?.keyword} footer={<Button variant="secondary" onClick={() => setSelected(null)}>Close</Button>}>
        {selected && (
          <div className="space-y-1">
            <Badge variant={selected.trend === 'up' ? 'green' : selected.trend === 'down' ? 'red' : 'slate'}>
              {selected.trend === 'up' ? 'Improving' : selected.trend === 'down' ? 'Declining' : 'Stable'}
            </Badge>
            <InfoRow label="Keyword" value={selected.keyword} />
            <InfoRow label="Current Rank" value={`#${selected.rank}`} />
            <InfoRow label="Previous Rank" value={`#${selected.previousRank}`} />
            <InfoRow label="Search Volume" value={selected.searchVolume.toLocaleString()} />
          </div>
        )}
      </Drawer>
    </div>
  );
}

